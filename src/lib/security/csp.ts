// Content Security Policy construction (Phase 4).
//
// The policy has two parts, emitted by different files:
//
//   * `Content-Security-Policy` (enforced baseline): a deliberately small
//     subset of directives that cannot break the application — it blocks
//     framing, plugin/object content and document base-URL changes. It is
//     emitted from next.config.ts for every response. It must not come from
//     src/proxy.ts: Next.js folds a response CSP header back into the render
//     request, so a nonce-less enforced header there would overwrite the
//     nonce-bearing request policy before Next tags its scripts.
//
//   * `Content-Security-Policy-Report-Only` (full policy): every directive
//     requested for the application, nonce-based for scripts, with no
//     'unsafe-eval' and no 'unsafe-inline' for scripts. It is emitted by
//     src/proxy.ts with a fresh nonce per request. Report-only never blocks a
//     request; violations surface in the browser console. See docs/security.md
//     for the checklist that must pass before it is promoted.
//
// Why the full policy is not enforced yet: this environment has no browser
// automation, so hydration, login, uploads, downloads and Razorpay Checkout
// cannot be exercised under the policy. A missed origin would silently break
// them. Report-only gives the same directive coverage for inspection without
// that risk.
//
// Notes on individual directives:
//   * script-src uses a cryptographically random nonce per request. Next.js
//     reads the nonce from the `Content-Security-Policy` request header that
//     proxy.ts forwards and tags its framework, page-bundle and inline
//     (streaming/hydration) scripts with it. 'strict-dynamic' lets those
//     trusted scripts load further chunks; the explicit Razorpay host is the
//     fallback for browsers without 'strict-dynamic' support.
//   * style-src keeps 'unsafe-inline'. React renders inline style attributes
//     (e.g. animation delays in src/app/page.tsx and the auth screens).
//     Adding a nonce to style-src would make browsers ignore 'unsafe-inline'
//     for style attributes and break those pages, so no nonce is used here.
//   * Razorpay Checkout is allowed as https://*.razorpay.com rather than a
//     fixed host list: checkout.js references checkout, api, cdn, lumberjack*
//     subdomains and builds a region-specific api host at runtime. A pinned
//     list would break checkout when Razorpay changes hosts.
//   * Google Fonts (stylesheet + font files) is the only other external
//     origin, used by src/app/layout.tsx.

import { randomBytes } from "node:crypto";

const GOOGLE_FONTS_STYLES = "https://fonts.googleapis.com";
const GOOGLE_FONTS_FILES = "https://fonts.gstatic.com";
const RAZORPAY_CHECKOUT = "https://*.razorpay.com";

/** Directives that are safe to enforce before browser validation. */
const ENFORCED_DIRECTIVES = [
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
] as const;

export interface ReportOnlyPolicyOptions {
  /** Per-request nonce generated by generateNonce(). */
  nonce: string;
  /** Development adds eval and HMR websocket allowances; production never does. */
  development?: boolean;
}

/**
 * 128 bits of cryptographic randomness, base64-encoded. A fresh value is
 * generated for every request; see tests/csp.test.mjs.
 */
export function generateNonce(): string {
  return randomBytes(16).toString("base64");
}

/**
 * Canonical enforced baseline. next.config.ts sets the same literal for every
 * response (it cannot import this module); tests/csp.test.mjs guards the two
 * against drift. Only directives that cannot impact rendering, scripts,
 * styles or the payment provider belong here — see the file header.
 */
export function buildEnforcedPolicy(): string {
  return ENFORCED_DIRECTIVES.join("; ");
}

/**
 * The full policy. Shipped as Content-Security-Policy-Report-Only until the
 * pre-enforcement checklist in docs/security.md passes in a browser.
 */
export function buildReportOnlyPolicy({ nonce, development = false }: ReportOnlyPolicyOptions): string {
  const directives = [
    "default-src 'self'",
    [
      "script-src 'self'",
      `'nonce-${nonce}'`,
      "'strict-dynamic'",
      RAZORPAY_CHECKOUT,
      development ? "'unsafe-eval'" : "",
    ]
      .filter(Boolean)
      .join(" "),
    `style-src 'self' 'unsafe-inline' ${GOOGLE_FONTS_STYLES}`,
    "img-src 'self' data: blob:",
    `font-src 'self' data: ${GOOGLE_FONTS_FILES}`,
    ["connect-src 'self'", RAZORPAY_CHECKOUT, development ? "ws: wss:" : ""]
      .filter(Boolean)
      .join(" "),
    `frame-src ${RAZORPAY_CHECKOUT}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ];

  if (!development) {
    // Development runs on plain HTTP locally; only production needs this.
    directives.push("upgrade-insecure-requests");
  }

  return directives.join("; ");
}
